const customIcon = L.icon({
    iconUrl: 'marker.png', // Путь к вашей картинке (PNG, SVG, JPG)
    iconSize: [32, 32],                // Размер иконки в пикселях [ширина, высота]
    iconAnchor: [16, 16],              // Точка иконки, которая будет указывать точно на координаты [X, Y]
    popupAnchor: [0, -38]              // Точка, откуда будет открываться всплывающее окно (относительно iconAnchor)
});

function createMarker(lat, lon, street, name, route = '#') {
    // Передаем объект { icon: customIcon } вторым аргументом в L.marker
    L.marker([lat, lon], { icon: customIcon })
        .addTo(map)
        .bindPopup(`
            <div class="marker-popup">
                <h2>${name}</h2>
                <h3>${street}</h3>
                
                <a href="${route}" class="map-btn">Узнать больше</a>
            </div>
        `);
}

